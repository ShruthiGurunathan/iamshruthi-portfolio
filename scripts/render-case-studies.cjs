const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const layout = read('_layouts/portfolio.html');
const baseURI = 'https://iamshruthi.com/';
const media = html => html.replaceAll('__PORTFOLIO_MEDIA__/', '/assets/media/');
const template = media(read('assets/case-studies/template.html'));
const router = layout.split('<script id="lives-lived-well-router">')[1].split('</script>')[0];
const buildCode = router.slice(router.indexOf('const projects='), router.indexOf('function syncTheme'));
const covers = new Map();
for (const row of layout.matchAll(/<article[^>]*data-case-page="([^"]+)"[^>]*>[\s\S]*?<\/article>/g)) {
  const src = row[0].match(/class="v160-hover-image"[^>]*src="([^"]+)"/)?.[1];
  if (src) covers.set(row[1], new URL(src, baseURI).href);
}
const document = {
  baseURI,
  querySelector(selector) {
    const slug = selector.match(/data-case-page="([^"]+)"/)?.[1];
    return covers.has(slug) ? {src: covers.get(slug)} : null;
  }
};
const {projects, projectDocument} = vm.runInNewContext(
  buildCode + '\n({projects, projectDocument})', {URL, document, caseUrl: slug => new URL(slug + '/', baseURI)}
);
const navigation = `<nav class="published-case-nav" aria-label="Portfolio">
  <a href="/">Shruthi Gurunathan</a>
  <div><a href="/#cases">Case studies</a><a href="/#about">About</a><a href="/#contact">Contact</a></div>
</nav>`;
const style = `<style>
:root{--paper:#f3f0e8;--ink:#b5440e;--line:rgba(181,68,14,.42);--hover-accent:#b5440e}
body.body-container{--_theme---background:var(--paper);--_theme---text:var(--ink);background:var(--paper);color:var(--ink)}
.published-case-nav{display:flex;flex-wrap:wrap;justify-content:space-between;align-items:center;gap:12px;padding:20px 6vw;border-bottom:1px solid var(--line);font-size:clamp(14px,1.5vw,18px)}
.published-case-nav div{display:flex;flex-wrap:wrap;gap:clamp(12px,3vw,34px)}
.published-case-nav a{color:inherit;text-decoration:none}
.published-case-nav a:is(:hover,:focus-visible){text-decoration:underline}
</style>`;

for (const [slug, project] of Object.entries(projects)) {
  const custom = slug === 'lives-lived-well' || slug === 'nutripaw';
  const content = custom ? JSON.parse(media(read('assets/case-studies/' + slug + '.json'))) : null;
  let html = projectDocument(project, template, content);
  // The shared design was originally displayed inside the portfolio iframe.
  // Give the standalone document its own navigation and remove iframe messaging.
  html = html
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, script =>
      /postMessage\s*\(|colorThemesReady/.test(script) ? '' : script)
    .replace(/<base\b[^>]*>/i, '')
    .replace(/<title>[\s\S]*?<\/title>/i, '<title>' + project.title + ' — Shruthi Gurunathan</title>')
    .replace(/(<body[^>]*><div class="page-wrap">)[\s\S]*?(?=<section class="case-study-hero">)/, '$1' + navigation + '<main>')
    .replace('</head>', style + '</head>');
  // Close the landmark at the end of the existing page wrapper.
  const footer = html.indexOf('<div class="marquee-wrapper footer');
  if (footer >= 0) html = html.slice(0, footer) + '</main>' + html.slice(footer);
  else html = html.replace('</body>', '</main></body>');
  if (!html.includes('<main>') || !html.includes('class="case-study-hero"') || html.includes('__PORTFOLIO_MEDIA__')) {
    throw new Error('Incomplete case study: ' + slug);
  }
  fs.writeFileSync(path.join(root, slug, 'index.html'), '<!doctype html>\n<!-- Generated by scripts/render-case-studies.cjs -->\n' + html.replace(/[ \t]+$/gm, ''));
}
